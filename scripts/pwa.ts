import { createHash } from 'node:crypto';
import { readdirSync } from 'node:fs';
import { join, relative } from 'node:path';
import type { Plugin } from 'vite';
import { iconSvg, readMessages, readTokens } from './brand.ts';

function publicFiles(dir: string, base = dir): string[] {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) =>
    entry.isDirectory() ? publicFiles(join(dir, entry.name), base) : [relative(base, join(dir, entry.name)).split('\\').join('/')],
  );
}

/**
 * Makes Qanvas installable and usable offline: a web app manifest, an SVG icon and the HTML
 * meta tags (colors from the design tokens, text from the English messages), plus a service
 * worker that caches every built file.
 */
export function pwa(root: string): Plugin {
  const tokens = readTokens(root);
  const messages = readMessages(root, 'en');

  const manifest = JSON.stringify(
    {
      name: messages['app.name'],
      short_name: messages['app.name'],
      description: messages['app.description'],
      lang: 'en',
      start_url: './',
      scope: './',
      display: 'standalone',
      background_color: tokens.ground,
      theme_color: tokens.brand,
      icons: [
        { src: 'icons/icon-192.png', sizes: '192x192', type: 'image/png' },
        { src: 'icons/icon-512.png', sizes: '512x512', type: 'image/png' },
        { src: 'icons/maskable-512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' },
        { src: 'icon.svg', sizes: 'any', type: 'image/svg+xml' },
      ],
    },
    null,
    2,
  );
  const icon = iconSvg(tokens);

  return {
    name: 'qanvas-pwa',

    transformIndexHtml() {
      return [
        { tag: 'meta', attrs: { name: 'description', content: messages['app.description'] }, injectTo: 'head' },
        { tag: 'meta', attrs: { name: 'theme-color', content: tokens.brand }, injectTo: 'head' },
        { tag: 'link', attrs: { rel: 'icon', href: 'icon.svg', type: 'image/svg+xml' }, injectTo: 'head' },
        { tag: 'link', attrs: { rel: 'apple-touch-icon', href: 'icons/apple-touch-icon.png' }, injectTo: 'head' },
        { tag: 'link', attrs: { rel: 'manifest', href: 'manifest.webmanifest' }, injectTo: 'head' },
      ];
    },

    configureServer(server) {
      server.middlewares.use((req, res, next) => {
        const path = req.url?.split('?')[0] ?? '';
        if (path.endsWith('/manifest.webmanifest')) res.setHeader('Content-Type', 'application/manifest+json').end(manifest);
        else if (path.endsWith('/icon.svg')) res.setHeader('Content-Type', 'image/svg+xml').end(icon);
        else next();
      });
    },

    generateBundle(_, bundle) {
      this.emitFile({ type: 'asset', fileName: 'manifest.webmanifest', source: manifest });
      this.emitFile({ type: 'asset', fileName: 'icon.svg', source: icon });

      const files = ['./', 'manifest.webmanifest', 'icon.svg', ...Object.keys(bundle), ...publicFiles(join(root, 'public'))]
        .filter((file) => file !== 'index.html')
        .sort();
      const html = bundle['index.html'];
      const version = createHash('sha256')
        .update(JSON.stringify(files))
        .update(html && html.type === 'asset' ? String(html.source) : '')
        .digest('hex')
        .slice(0, 12);
      this.emitFile({ type: 'asset', fileName: 'sw.js', source: serviceWorker(`qanvas-${version}`, files) });
    },
  };
}

function serviceWorker(cache: string, files: string[]): string {
  return `// Generated by scripts/pwa.ts.
const CACHE = ${JSON.stringify(cache)};
const FILES = ${JSON.stringify(files)};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(FILES)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((key) => key.startsWith('qanvas-') && key !== CACHE).map((key) => caches.delete(key))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET' || new URL(request.url).origin !== self.location.origin) return;
  // Pages come from the network when it's there, so a new version shows up on the next visit.
  if (request.mode === 'navigate') {
    event.respondWith(fetch(request).catch(() => caches.match(new URL('./', self.location).href, { ignoreVary: true })));
    return;
  }
  // Some servers add "Vary: Origin", which would make cached files miss for script and style tags.
  event.respondWith(caches.match(request, { ignoreVary: true }).then((hit) => hit || fetch(request)));
});
`;
}
